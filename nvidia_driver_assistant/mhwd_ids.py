
"""Generate and audit Manjaro MHWD NVIDIA PCI ID lists."""

from collections import Counter
import os
import re

from . import supported_chips


DEFAULT_IDS_DIR = "/var/lib/mhwd/ids/pci"
IDS_HEADER = "# List generated by mhwd. Do not edit manually."

ID_TOKEN_RE = re.compile(r"^(?:0x)?([0-9a-f]{4})$", re.IGNORECASE)

DRIVER_FILES = {
    "latest": "nvidia.ids",
    "580": "nvidia-580xx.ids",
    "470": "nvidia-470xx.ids",
    "390": "nvidia-390xx.ids",
    "340": "nvidia-340xx.ids",
}

DRIVER_ORDER = ("latest", "580", "470", "390", "340")


def normalize_branch(branch):
    """Return a canonical target branch name."""
    value = str(branch).strip().lower()

    if value in ("6xx", "latest"):
        return "latest"

    if value not in DRIVER_FILES:
        raise ValueError(
            "Unsupported NVIDIA driver branch: %s. Supported branches: "
            "latest (or 6xx), 580, 470, 390 and 340."
            % branch
        )

    return value


def _get_document_ids(branch):
    """Return only the GPU IDs supported by the selected driver branch."""
    branch = normalize_branch(branch)

    if branch == "latest":
        path = supported_chips._CHIPS_FILE
        device_ids = supported_chips.parse_current(path)

    elif branch == "580":
        path = supported_chips._CHIPS_580_FILE
        device_ids = supported_chips.parse_current(path)

    elif branch == "470":
        path = supported_chips._CHIPS_470_FILE
        device_ids = supported_chips.parse_legacy_supportedchips(path)

    elif branch == "390":
        path = supported_chips._CHIPS_390_FILE
        device_ids = supported_chips.parse_legacy_supportedchips(path)

    else:
        path = supported_chips._CHIPS_340_FILE
        device_ids = supported_chips.parse_legacy_supportedchips(path)

    if not device_ids:
        raise ValueError(
            "Could not parse NVIDIA %s supported-device IDs from %s"
            % (branch, path)
        )

    normalized = set()

    for device_id in device_ids:
        value = str(device_id).strip().lower()

        if value.startswith("0x"):
            value = value[2:]

        if not re.fullmatch(r"[0-9a-f]{4}", value):
            raise ValueError(
                "Invalid PCI Device ID returned for NVIDIA %s: %r"
                % (branch, device_id)
            )

        normalized.add(value)

    if not normalized:
        raise ValueError(
            "NVIDIA %s document produced an empty device-ID list" % branch
        )

    return normalized


def generate_ids(branch):
    """Return one MHWD .ids file as text; never writes to the filesystem.

    The caller, normally the NVIDIA utils PKGBUILD, redirects stdout into
    the package staging directory. This keeps package generation separate
    from the live system's /var/lib/mhwd database.
    """
    branch = normalize_branch(branch)
    device_ids = sorted(_get_document_ids(branch))

    return (
        IDS_HEADER
        + "\n"
        + " ".join(device_ids)
        + "\n"
    )


def _resolve_ids_dir(ids_dir=None):
    """Resolve the directory used by the read-only checker."""
    if ids_dir is None:
        ids_dir = DEFAULT_IDS_DIR

    return os.path.abspath(os.path.expanduser(ids_dir))


def _read_ids_file(path):
    """Read MHWD IDs, returning occurrence counts and malformed tokens."""
    counts = Counter()
    invalid_tokens = []

    with open(path, "r", encoding="utf-8", errors="replace") as stream:
        for line_number, line in enumerate(stream, 1):
            data = line.split("#", 1)[0]

            for token in data.split():
                match = ID_TOKEN_RE.fullmatch(token)

                if not match:
                    invalid_tokens.append(
                        "%d:%s" % (line_number, token)
                    )
                    continue

                counts[match.group(1).lower()] += 1

    return counts, invalid_tokens


def check_ids(ids_dir=None):
    """Audit existing target .ids files without changing any file."""
    target_dir = _resolve_ids_dir(ids_dir)

    if not os.path.isdir(target_dir):
        raise FileNotFoundError(
            "MHWD IDs directory does not exist: %s" % target_dir
        )

    reports = []

    for branch in DRIVER_ORDER:
        filename = DRIVER_FILES[branch]
        path = os.path.join(target_dir, filename)

        # The presence of a branch-specific .ids file is optional.
        if not os.path.lexists(path):
            continue

        report = {
            "branch": branch,
            "filename": filename,
            "path": path,
        }

        if not os.path.isfile(path):
            report["error"] = "Not a regular file"
            reports.append(report)
            continue

        try:
            counts, invalid_tokens = _read_ids_file(path)
            documented_ids = _get_document_ids(branch)

        except (OSError, ValueError) as exc:
            report["error"] = str(exc)
            reports.append(report)
            continue

        listed_ids = set(counts)
        missing_ids = documented_ids - listed_ids
        undocumented_ids = listed_ids - documented_ids

        duplicate_ids = {
            device_id
            for device_id, count in counts.items()
            if count > 1
        }

        report.update(
            {
                "listed_count": len(listed_ids),
                "documented_count": len(documented_ids),
                "missing_ids": sorted(missing_ids),
                "undocumented_ids": sorted(undocumented_ids),
                "duplicate_ids": sorted(duplicate_ids),
                "invalid_tokens": invalid_tokens,
                "matches": not (
                    missing_ids
                    or undocumented_ids
                    or duplicate_ids
                    or invalid_tokens
                ),
            }
        )

        reports.append(report)

    if not reports:
        raise FileNotFoundError(
            "No target NVIDIA .ids files found in %s. "
            "Expected one or more of: %s"
            % (
                target_dir,
                ", ".join(DRIVER_FILES.values()),
            )
        )

    return reports
