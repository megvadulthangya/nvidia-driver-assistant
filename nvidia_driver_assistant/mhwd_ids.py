"""Generate and audit Manjaro MHWD NVIDIA PCI ID lists."""

from collections import Counter
import os
import re
import tempfile

from . import supported_chips


DEFAULT_IDS_DIR = "/var/lib/mhwd/ids/pci"

IDS_HEADER = "# List generated by mhwd. Do not edit manually."

ID_TOKEN_RE = re.compile(
    r"^(?:0x)?([0-9a-f]{4})$",
    re.IGNORECASE,
)

DRIVER_FILES = {
    "6xx": "nvidia.ids",
    "580": "nvidia-580xx.ids",
    "470": "nvidia-470xx.ids",
    "390": "nvidia-390xx.ids",
    "340": "nvidia-340xx.ids",
}

DRIVER_ORDER = ("6xx", "580", "470", "390", "340")


def normalize_branch(branch):
    """Normalize a driver branch name.

    'latest' is accepted as an alias for the current 6xx driver.
    """
    value = str(branch).strip().lower()

    if value == "latest":
        value = "6xx"

    if value not in DRIVER_FILES:
        raise ValueError(
            "Unsupported NVIDIA driver branch: %s. "
            "Supported branches: 6xx, 580, 470, 390, 340."
            % branch
        )

    return value


def _get_document_ids(branch):
    """Read the supported device IDs for one target driver branch.

    The latest document contributes only its Current section.
    The 580 document also contributes only its Current section.
    Older documents contribute all product tables belonging to their
    own driver branch, stopping at NVIDIA's legacy-section boundary.
    """
    branch = normalize_branch(branch)

    if branch == "6xx":
        path = supported_chips._CHIPS_FILE
        ids = supported_chips.parse_current(path)

    elif branch == "580":
        path = supported_chips._CHIPS_580_FILE
        ids = supported_chips.parse_current(path)

    elif branch == "470":
        path = supported_chips._CHIPS_470_FILE
        ids = supported_chips.parse_legacy_supportedchips(path)

    elif branch == "390":
        path = supported_chips._CHIPS_390_FILE
        ids = supported_chips.parse_legacy_supportedchips(path)

    else:
        path = supported_chips._CHIPS_340_FILE
        ids = supported_chips.parse_legacy_supportedchips(path)

    if not ids:
        raise ValueError(
            "Could not parse NVIDIA %s supported device IDs from %s"
            % (branch, path)
        )

    normalized = set()

    for device_id in ids:
        value = str(device_id).strip().lower()

        if value.startswith("0x"):
            value = value[2:]

        if not re.fullmatch(r"[0-9a-f]{4}", value):
            raise ValueError(
                "Invalid PCI Device ID returned by the %s parser: %r"
                % (branch, device_id)
            )

        normalized.add(value)

    if not normalized:
        raise ValueError(
            "NVIDIA %s document produced an empty device ID list"
            % branch
        )

    return normalized


def _resolve_ids_dir(ids_dir=None):
    """Return the absolute MHWD IDs directory."""
    if ids_dir is None:
        ids_dir = DEFAULT_IDS_DIR

    return os.path.abspath(os.path.expanduser(ids_dir))


def generate_ids(branch, ids_dir=None):
    """Generate exactly one MHWD NVIDIA .ids file.

    Existing files belonging to other driver branches are never modified.
    The target file is replaced atomically after successful parsing.
    """
    branch = normalize_branch(branch)
    target_dir = _resolve_ids_dir(ids_dir)
    filename = DRIVER_FILES[branch]
    target_path = os.path.join(target_dir, filename)

    # Parse and validate the document before touching the output directory.
    device_ids = _get_document_ids(branch)
    ordered_ids = sorted(device_ids)

    os.makedirs(target_dir, exist_ok=True)

    if os.path.islink(target_path):
        raise ValueError(
            "Refusing to replace a symbolic link: %s" % target_path
        )

    if os.path.lexists(target_path) and not os.path.isfile(target_path):
        raise ValueError(
            "The target exists but is not a regular file: %s" % target_path
        )

    content = (
        IDS_HEADER
        + "\n"
        + " ".join(ordered_ids)
        + "\n"
    )

    temporary_path = None

    try:
        file_descriptor, temporary_path = tempfile.mkstemp(
            prefix=".%s." % filename,
            suffix=".tmp",
            dir=target_dir,
        )

        with os.fdopen(
            file_descriptor,
            "w",
            encoding="ascii",
            newline="\n",
        ) as stream:
            stream.write(content)

        os.chmod(temporary_path, 0o644)
        os.replace(temporary_path, target_path)
        temporary_path = None

    finally:
        if temporary_path and os.path.exists(temporary_path):
            os.unlink(temporary_path)

    return {
        "branch": branch,
        "filename": filename,
        "path": target_path,
        "count": len(ordered_ids),
    }


def _read_ids_file(path):
    """Read an MHWD .ids file and return its IDs and duplicate entries.

    The normal MHWD format consists of comments and whitespace-separated
    four-character hexadecimal PCI Device IDs.
    """
    counts = Counter()
    invalid_tokens = []

    with open(path, "r", encoding="utf-8", errors="replace") as stream:
        for line_number, line in enumerate(stream, 1):
            # Ignore comments, including the normal MHWD header.
            data = line.split("#", 1)[0]

            for token in data.split():
                match = ID_TOKEN_RE.fullmatch(token)

                if not match:
                    invalid_tokens.append(
                        "%d:%s" % (line_number, token)
                    )
                    continue

                device_id = match.group(1).lower()
                counts[device_id] += 1

    return counts, invalid_tokens


def check_ids(ids_dir=None):
    """Audit all existing target NVIDIA .ids files without modifying them.

    Missing branch files are deliberately ignored. Only files that actually
    exist in the target directory are checked.

    IDs not present in NVIDIA's corresponding document are reported for
    manual review. They are not automatically classified as invalid hardware
    IDs because NVIDIA's documentation may be incomplete.
    """
    target_dir = _resolve_ids_dir(ids_dir)

    if not os.path.isdir(target_dir):
        raise FileNotFoundError(
            "MHWD IDs directory does not exist: %s" % target_dir
        )

    reports = []

    for branch in DRIVER_ORDER:
        filename = DRIVER_FILES[branch]
        path = os.path.join(target_dir, filename)

        # A branch is optional. Do not require all five files to exist.
        if not os.path.lexists(path):
            continue

        report = {
            "branch": branch,
            "filename": filename,
            "path": path,
        }

        if not os.path.isfile(path):
            report["error"] = "Not a regular file"
            reports.append(report)
            continue

        try:
            counts, invalid_tokens = _read_ids_file(path)
            documented_ids = _get_document_ids(branch)

        except (OSError, ValueError) as exc:
            report["error"] = str(exc)
            reports.append(report)
            continue

        listed_ids = set(counts)

        missing_ids = documented_ids - listed_ids
        undocumented_ids = listed_ids - documented_ids
        duplicate_ids = {
            device_id
            for device_id, count in counts.items()
            if count > 1
        }

        report.update(
            {
                "listed_count": len(listed_ids),
                "documented_count": len(documented_ids),
                "missing_ids": sorted(missing_ids),
                "undocumented_ids": sorted(undocumented_ids),
                "duplicate_ids": sorted(duplicate_ids),
                "invalid_tokens": invalid_tokens,
                "matches": (
                    not missing_ids
                    and not undocumented_ids
                    and not duplicate_ids
                    and not invalid_tokens
                ),
            }
        )

        reports.append(report)

    if not reports:
        raise FileNotFoundError(
            "No target NVIDIA .ids files found in %s. "
            "The checker looks for: %s"
            % (
                target_dir,
                ", ".join(DRIVER_FILES.values()),
            )
        )

    return reports
