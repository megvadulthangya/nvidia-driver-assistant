import os
import pathlib
import tempfile
import unittest
from unittest.mock import patch

from nvidia_driver_assistant import mhwd_ids
from nvidia_driver_assistant import cli


class GenerateMHWDIDsTests(unittest.TestCase):

    def test_generate_creates_only_the_selected_branch(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191", "0FEF", "062E"},
            ) as parser:
                result = mhwd_ids.generate_ids("340", tmpdir)

            parser.assert_called_once_with("340")

            expected_path = pathlib.Path(tmpdir) / "nvidia-340xx.ids"

            self.assertTrue(expected_path.is_file())
            self.assertEqual(result["branch"], "340")
            self.assertEqual(result["filename"], "nvidia-340xx.ids")
            self.assertEqual(result["count"], 3)

            content = expected_path.read_text(encoding="ascii")

            self.assertEqual(
                content,
                (
                    "# List generated by mhwd. Do not edit manually.\n"
                    "0191 062e 0fef\n"
                ),
            )

            self.assertEqual(
                sorted(os.listdir(tmpdir)),
                ["nvidia-340xx.ids"],
            )

    def test_latest_alias_generates_nvidia_ids(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"1e02", "31c3"},
            ) as parser:
                result = mhwd_ids.generate_ids("latest", tmpdir)

            parser.assert_called_once_with("6xx")
            self.assertEqual(result["branch"], "6xx")
            self.assertEqual(result["filename"], "nvidia.ids")

            content = (
                pathlib.Path(tmpdir) / "nvidia.ids"
            ).read_text(encoding="ascii")

            self.assertIn("1e02 31c3", content)

    def test_generate_does_not_modify_other_branch_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            other_path = pathlib.Path(tmpdir) / "nvidia-470xx.ids"
            other_path.write_text(
                "existing 470 contents\n",
                encoding="ascii",
            )

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191"},
            ):
                mhwd_ids.generate_ids("340", tmpdir)

            self.assertEqual(
                other_path.read_text(encoding="ascii"),
                "existing 470 contents\n",
            )

    def test_invalid_branch_is_rejected(self):
        with self.assertRaises(ValueError):
            mhwd_ids.generate_ids("304", "/tmp/mhwd-test")

    def test_empty_document_result_is_rejected_before_writing(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                side_effect=ValueError("empty document"),
            ):
                with self.assertRaises(ValueError):
                    mhwd_ids.generate_ids("580", tmpdir)

            self.assertEqual(os.listdir(tmpdir), [])


class CheckMHWDIDsTests(unittest.TestCase):

    def test_check_only_audits_existing_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia.ids"
            path.write_text(
                (
                    "# List generated by mhwd. Do not edit manually.\n"
                    "0191 1e02\n"
                ),
                encoding="ascii",
            )

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191", "1e02"},
            ) as parser:
                reports = mhwd_ids.check_ids(tmpdir)

            parser.assert_called_once_with("6xx")

            self.assertEqual(len(reports), 1)
            self.assertEqual(reports[0]["branch"], "6xx")
            self.assertTrue(reports[0]["matches"])

    def test_check_reports_differences_without_modifying_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia.ids"
            original = (
                "# List generated by mhwd. Do not edit manually.\n"
                "0191 0191 ffff\n"
            )
            path.write_text(original, encoding="ascii")

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191", "1e02"},
            ):
                reports = mhwd_ids.check_ids(tmpdir)

            report = reports[0]

            self.assertFalse(report["matches"])
            self.assertEqual(report["missing_ids"], ["1e02"])
            self.assertEqual(report["undocumented_ids"], ["ffff"])
            self.assertEqual(report["duplicate_ids"], ["0191"])

            # The checker must be strictly read-only.
            self.assertEqual(path.read_text(encoding="ascii"), original)

    def test_check_reports_unrecognized_tokens(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia.ids"
            path.write_text(
                "0191 not-a-pci-id\n",
                encoding="ascii",
            )

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191"},
            ):
                reports = mhwd_ids.check_ids(tmpdir)

            self.assertEqual(
                reports[0]["invalid_tokens"],
                ["1:not-a-pci-id"],
            )
            self.assertFalse(reports[0]["matches"])

    def test_check_does_not_require_all_five_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia-390xx.ids"
            path.write_text("06c0 118a\n", encoding="ascii")

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"06c0", "118a"},
            ) as parser:
                reports = mhwd_ids.check_ids(tmpdir)

            parser.assert_called_once_with("390")
            self.assertEqual(len(reports), 1)
            self.assertEqual(reports[0]["branch"], "390")

    def test_check_fails_when_no_target_files_exist(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            with self.assertRaises(FileNotFoundError):
                mhwd_ids.check_ids(tmpdir)

    def test_check_fails_when_directory_does_not_exist(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            missing = os.path.join(tmpdir, "does-not-exist")

            with self.assertRaises(FileNotFoundError):
                mhwd_ids.check_ids(missing)


class MHWDIDsCLITests(unittest.TestCase):

    def test_generate_option_dispatches_without_hardware_detection(self):
        result = {
            "branch": "580",
            "filename": "nvidia-580xx.ids",
            "path": "/tmp/nvidia-580xx.ids",
            "count": 123,
        }

        with patch.object(cli, "generate_ids", return_value=result) as generate:
            with patch(
                "sys.argv",
                [
                    "nvidia-driver-assistant",
                    "--generate-ids",
                    "580",
                    "--ids-dir",
                    "/tmp/ids",
                ],
            ):
                cli.main()

        generate.assert_called_once_with(
            "580",
            ids_dir="/tmp/ids",
        )

    def test_check_option_dispatches_without_hardware_detection(self):
        reports = [
            {
                "branch": "6xx",
                "filename": "nvidia.ids",
                "path": "/tmp/nvidia.ids",
                "listed_count": 2,
                "documented_count": 2,
                "missing_ids": [],
                "undocumented_ids": [],
                "duplicate_ids": [],
                "invalid_tokens": [],
                "matches": True,
            }
        ]

        with patch.object(cli, "check_ids", return_value=reports) as checker:
            with patch(
                "sys.argv",
                [
                    "nvidia-driver-assistant",
                    "--check-ids",
                    "--ids-dir",
                    "/tmp/ids",
                ],
            ):
                cli.main()

        checker.assert_called_once_with(ids_dir="/tmp/ids")


if __name__ == "__main__":
    unittest.main(verbosity=2)
