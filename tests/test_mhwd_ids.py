
import contextlib
import io
import os
import pathlib
import tempfile
import unittest
from unittest.mock import patch

from nvidia_driver_assistant import cli, mhwd_ids


class GenerateMHWDIDsTests(unittest.TestCase):

    def test_generate_returns_mhwd_format_and_does_not_write_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191", "0fef", "062e"},
            ) as get_ids:
                output = mhwd_ids.generate_ids("340")

            get_ids.assert_called_once_with("340")

            self.assertEqual(
                output,
                (
                    "# List generated by mhwd. Do not edit manually.\n"
                    "0191 062e 0fef\n"
                ),
            )

            self.assertEqual(os.listdir(tmpdir), [])

    def test_latest_and_6xx_aliases_generate_latest_ids(self):
        with patch.object(
            mhwd_ids,
            "_get_document_ids",
            return_value={"1e02", "31c3"},
        ) as get_ids:
            output = mhwd_ids.generate_ids("6xx")

        get_ids.assert_called_once_with("latest")
        self.assertTrue(output.endswith("1e02 31c3\n"))

    def test_latest_uses_only_latest_current_document(self):
        with patch.object(
            mhwd_ids.supported_chips,
            "parse_current",
            return_value={"1e02", "31c3"},
        ) as parser:
            ids = mhwd_ids._get_document_ids("latest")

        parser.assert_called_once_with(
            mhwd_ids.supported_chips._CHIPS_FILE
        )
        self.assertEqual(ids, {"1e02", "31c3"})

    def test_580_uses_580_document_current_list(self):
        with patch.object(
            mhwd_ids.supported_chips,
            "parse_current",
            return_value={"1340", "2d18"},
        ) as parser:
            ids = mhwd_ids._get_document_ids("580")

        parser.assert_called_once_with(
            mhwd_ids.supported_chips._CHIPS_580_FILE
        )
        self.assertEqual(ids, {"1340", "2d18"})

    def test_older_branches_use_their_own_document_parser(self):
        cases = (
            ("470", "_CHIPS_470_FILE"),
            ("390", "_CHIPS_390_FILE"),
            ("340", "_CHIPS_340_FILE"),
        )

        for branch, path_attribute in cases:
            with self.subTest(branch=branch):
                source_path = getattr(
                    mhwd_ids.supported_chips,
                    path_attribute,
                )

                with patch.object(
                    mhwd_ids.supported_chips,
                    "parse_legacy_supportedchips",
                    return_value={"0fc6", "0191"},
                ) as parser:
                    ids = mhwd_ids._get_document_ids(branch)

                parser.assert_called_once_with(source_path)
                self.assertEqual(ids, {"0fc6", "0191"})

    def test_invalid_branch_is_rejected(self):
        with self.assertRaises(ValueError):
            mhwd_ids.generate_ids("304")

    def test_empty_document_is_rejected(self):
        with patch.object(
            mhwd_ids,
            "_get_document_ids",
            side_effect=ValueError("empty source document"),
        ):
            with self.assertRaisesRegex(
                ValueError,
                "empty source document",
            ):
                mhwd_ids.generate_ids("580")


class CheckMHWDIDsTests(unittest.TestCase):

    def test_check_audits_existing_file_without_modifying_it(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia.ids"
            original = (
                "# List generated by mhwd. Do not edit manually.\n"
                "0191 1e02\n"
            )
            path.write_text(original, encoding="ascii")

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191", "1e02"},
            ) as get_ids:
                reports = mhwd_ids.check_ids(tmpdir)

            get_ids.assert_called_once_with("latest")
            self.assertEqual(len(reports), 1)
            self.assertTrue(reports[0]["matches"])

            # The audit must not change the original file.
            self.assertEqual(
                path.read_text(encoding="ascii"),
                original,
            )

    def test_check_reports_missing_undocumented_and_duplicate_ids(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia.ids"
            original = "0191 0191 ffff\n"
            path.write_text(original, encoding="ascii")

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191", "1e02"},
            ):
                reports = mhwd_ids.check_ids(tmpdir)

            report = reports[0]

            self.assertFalse(report["matches"])
            self.assertEqual(report["missing_ids"], ["1e02"])
            self.assertEqual(report["undocumented_ids"], ["ffff"])
            self.assertEqual(report["duplicate_ids"], ["0191"])

            self.assertEqual(
                path.read_text(encoding="ascii"),
                original,
            )

    def test_check_reports_unrecognized_tokens(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia.ids"
            path.write_text("0191 bad-token\n", encoding="ascii")

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"0191"},
            ):
                reports = mhwd_ids.check_ids(tmpdir)

            self.assertEqual(
                reports[0]["invalid_tokens"],
                ["1:bad-token"],
            )

    def test_check_does_not_require_all_five_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            path = pathlib.Path(tmpdir) / "nvidia-390xx.ids"
            path.write_text("06c0 118a\n", encoding="ascii")

            with patch.object(
                mhwd_ids,
                "_get_document_ids",
                return_value={"06c0", "118a"},
            ) as get_ids:
                reports = mhwd_ids.check_ids(tmpdir)

            get_ids.assert_called_once_with("390")
            self.assertEqual(len(reports), 1)
            self.assertEqual(reports[0]["branch"], "390")

    def test_check_errors_when_directory_is_missing_or_has_no_target_files(self):
        with tempfile.TemporaryDirectory() as tmpdir:
            missing_dir = os.path.join(tmpdir, "missing")

            with self.assertRaises(FileNotFoundError):
                mhwd_ids.check_ids(missing_dir)

            with self.assertRaises(FileNotFoundError):
                mhwd_ids.check_ids(tmpdir)


class MHWDIDsCLITests(unittest.TestCase):

    def test_generate_writes_only_ids_payload_to_stdout(self):
        payload = (
            "# List generated by mhwd. Do not edit manually.\n"
            "0191 0fef\n"
        )
        stdout = io.StringIO()

        with patch.object(
            cli,
            "generate_ids",
            return_value=payload,
        ) as generate:
            with patch(
                "sys.argv",
                [
                    "nvidia-driver-assistant",
                    "--generate-ids",
                    "340",
                ],
            ):
                with contextlib.redirect_stdout(stdout):
                    cli.main()

        generate.assert_called_once_with("340")
        self.assertEqual(stdout.getvalue(), payload)

    def test_check_uses_read_only_checker(self):
        reports = [
            {
                "branch": "latest",
                "filename": "nvidia.ids",
                "path": "/tmp/nvidia.ids",
                "listed_count": 1,
                "documented_count": 1,
                "missing_ids": [],
                "undocumented_ids": [],
                "duplicate_ids": [],
                "invalid_tokens": [],
                "matches": True,
            }
        ]
        stdout = io.StringIO()

        with patch.object(
            cli,
            "check_ids",
            return_value=reports,
        ) as checker:
            with patch(
                "sys.argv",
                [
                    "nvidia-driver-assistant",
                    "--check-ids",
                ],
            ):
                with contextlib.redirect_stdout(stdout):
                    cli.main()

        checker.assert_called_once_with(ids_dir=None)
        self.assertIn(
            "The audit did not modify any .ids file.",
            stdout.getvalue(),
        )

    def test_ids_dir_is_not_accepted_for_generation(self):
        with patch(
            "sys.argv",
            [
                "nvidia-driver-assistant",
                "--generate-ids",
                "580",
                "--ids-dir",
                "/tmp/ids",
            ],
        ):
            with self.assertRaises(SystemExit) as raised:
                cli.main()

        self.assertEqual(raised.exception.code, 2)


if __name__ == "__main__":
    unittest.main(verbosity=2)
